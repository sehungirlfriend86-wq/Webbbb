export function formatDateLocale(isoString: string, lang: Language = 'id'): string {
  try {
    const date = new Date(isoString);
    return date.toLocaleDateString(lang === 'en' ? 'en-US' : 'id-ID', {
      day: 'numeric',
      month: 'short',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    });
  } catch {
    return isoString;
  }
}

